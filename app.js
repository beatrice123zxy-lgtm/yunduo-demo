function 造节点(标签名, 类名, 文字) {
  var 节点 = document.createElement(标签名);
  if (类名) 节点.className = 类名;
  if (文字 !== undefined && 文字 !== null) 节点.textContent = 文字;
  return 节点;
}

function 渲染一张指标卡(指标) {
  var 卡类 = "指标卡";
  if (指标.名称 === "信息泄露次数") 卡类 += " 泄露";
  if (指标.告警) 卡类 += " 告警";
  var 卡 = 造节点("article", 卡类);
  卡.appendChild(造节点("h3", "指标名", 指标.名称));
  卡.appendChild(造节点("p", "百分比", 指标.百分比));
  卡.appendChild(造节点("p", "分子分母", 指标.分子 + " / " + 指标.分母));
  if (指标.名称 === "信息泄露次数") {
    卡.appendChild(造节点("p", "次数", "泄露 " + 指标.分子 + " 次（要求为 0）"));
  }
  卡.appendChild(造节点("p", "口径", 指标.口径));
  return 卡;
}

function 渲染评测结果(结果) {
  var 容器 = document.getElementById("评测结果");
  容器.innerHTML = "";

  var 指标行 = 造节点("div", "指标行");
  指标行.appendChild(渲染一张指标卡(结果.回答准确率));
  指标行.appendChild(渲染一张指标卡(结果.技能调用成功率));
  指标行.appendChild(渲染一张指标卡(结果.信息泄露次数));
  容器.appendChild(指标行);

  var 未通过区 = 造节点("div", "未通过区" + (结果.未通过.length ? " 有" : ""));
  未通过区.appendChild(造节点("h3", "", 结果.未通过.length ? "本次未通过" : "本次未通过：无"));
  if (结果.未通过.length) {
    var 列表 = 造节点("ul", "");
    结果.未通过.forEach(function (说明) {
      列表.appendChild(造节点("li", "", 说明));
    });
    未通过区.appendChild(列表);
  }
  容器.appendChild(未通过区);

  var 表格外包 = 造节点("div", "表格外包");
  var 表 = 造节点("table", "评测表");
  var 表头 = 造节点("tr", "");
  ["序号", "账号", "用户问题", "期望行为", "实际行为", "结果"].forEach(function (标题) {
    表头.appendChild(造节点("th", "", 标题));
  });
  var 头部 = 造节点("thead", "");
  头部.appendChild(表头);
  表.appendChild(头部);

  var 表体 = 造节点("tbody", "");
  结果.行.forEach(function (行) {
    var tr = 造节点("tr", 行.通过 ? "" : "未通过");
    tr.appendChild(造节点("td", "", String(行.序号)));
    tr.appendChild(造节点("td", "", 行.账号名));
    tr.appendChild(造节点("td", "", 行.问题));
    tr.appendChild(造节点("td", "", 行.期望行为));
    tr.appendChild(造节点("td", "", 行.实际行为));
    tr.appendChild(造节点("td", 行.通过 ? "通过标记" : "未通过标记", 行.通过 ? "通过" : "未通过"));
    表体.appendChild(tr);
  });
  表.appendChild(表体);
  表格外包.appendChild(表);
  容器.appendChild(表格外包);
}

