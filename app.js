function 发送(文字) {
  文字 = 文字.trim();
  if (!文字) return;
  添加用户消息(文字);
  输入框.value = "";

  当前轮次 += 1;
  var 本轮 = 当前轮次;
  var 回答 = 生成回答(文字, 当前账号());
  添加机器人消息(回答);
  显示本轮步骤(回答.步骤);

  // 超时的回答带有"补推"：到点后，机器人主动再发一条。点"快进补推"可以立刻发
  if (回答.补推) {
    安排补推(回答.补推, 本轮);
  }
}

