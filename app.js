function 取消所有补推() {
  待补推列表.forEach(function (记录) { clearTimeout(记录.定时器); });
  待补推列表 = [];
  更新快进按钮();
}

// 真正把【补推】发到聊天里。倒计时到点、或点"快进补推"，都走这里。
// 只有面板上还是发起这次查询的那一轮时，才往右边追加一步；
// 用户已经问了新问题的话，右边保持新的一轮，不被这条补推盖掉。
function 发出补推(记录) {
  var 位置 = 待补推列表.indexOf(记录);
  if (位置 === -1) return;
  clearTimeout(记录.定时器);
  待补推列表.splice(位置, 1);
  更新快进按钮();
  添加机器人消息(记录.回答);
  if (记录.轮次 === 当前轮次) {
    追加步骤(步骤("系统", "后台重试成功，推送补推消息"));
  }
}

function 安排补推(补推, 轮次) {
  var 记录 = { 回答: 补推.回答, 轮次: 轮次, 定时器: null };
  记录.定时器 = setTimeout(function () { 发出补推(记录); }, 补推.延迟毫秒);
  待补推列表.push(记录);
  更新快进按钮();
}

function 快进补推() {
  if (待补推列表.length === 0) return;
  发出补推(待补推列表[0]);
}

// 切换账号。是否清空：手动切换时清空对话；点示例按钮自动切换时保留对话
