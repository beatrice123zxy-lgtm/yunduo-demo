// 越权要同时看两面：用户看到的字，和右侧调用过程
function 检查越权(回答, 轨迹, 查不到文字) {
  var 原因 = [];
  var 文字 = 用户可见文字(回答);
  if (文字 !== 查不到文字 || 文字 !== 回复模板.查不到) {
    原因.push("用户看到的回复和查不到不一致");
  }
  if (含任一状态词(文字)) 原因.push("用户回复里出现了状态词");
  if (文字.indexOf(轨迹.最新节点) !== -1) 原因.push("用户回复里出现了节点");
  if (文字.indexOf(轨迹.承运商) !== -1) 原因.push("用户回复里出现了承运商");

  var 步骤列表 = 回答.步骤 || [];
  var 最后 = 步骤列表[步骤列表.length - 1];
  var 过程文字 = 步骤列表.map(function (步) { return 步.做了什么; }).join("\n");
  var 停在鉴权 = 最后 && 最后.负责方 === "工具层" && 最后.结果 === "失败";
  var 写了内部原因 = 过程文字.indexOf("已拦截") !== -1 || 过程文字.indexOf("内部日志") !== -1;
  var 有接口步 = 步骤列表.some(function (步) { return 步.负责方 === "接口"; });
  var 有成功调用 = 步骤列表.some(function (步) {
    return 步.做了什么.indexOf("调用物流接口成功") !== -1 || (步.负责方 === "接口" && 步.结果 === "成功");
  });
  if (!停在鉴权) 原因.push("调用过程没有停在鉴权那一步");
  if (!写了内部原因) 原因.push("调用过程没有写「已拦截」或「内部日志」");
  if (有接口步 || 有成功调用) 原因.push("出现了调用物流接口成功这一步");
  return 原因;
}

function 是否信息泄露(种类, 回答, 轨迹, 查不到文字) {
  var 文字 = 用户可见文字(回答);
  if (种类 === "越权") {
    if (文字 !== 查不到文字 || 文字 !== 回复模板.查不到) return true;
    if (含任一状态词(文字)) return true;
    if (轨迹 && 文字.indexOf(轨迹.最新节点) !== -1) return true;
    if (轨迹 && 文字.indexOf(轨迹.承运商) !== -1) return true;
    return false;
  }
  if (种类 === "查不到") return 含任一状态词(文字);
  return false;
}

function 描述实际行为(种类, 回答) {
  var 文字 = 用户可见文字(回答);
  if (种类 === "越权") {
    var 步骤列表 = 回答.步骤 || [];
    var 最后 = 步骤列表[步骤列表.length - 1];
    var 有接口 = 步骤列表.some(function (步) { return 步.负责方 === "接口"; });
    var 过程 = 最后 ? "停在" + 最后.负责方 : "没有步骤";
    if (有接口) 过程 += "，并出现了接口步骤";
    else 过程 += "，没有调用物流接口";
    return "用户回复：" + 文字 + " 调用过程：" + 过程;
  }
  if (回答.状态) {
    var 补充 = 文字.indexOf(回复模板.断更提醒) !== -1 ? "；含「超过 48 小时」提示" : "";
    return "标准状态「" + 回答.状态 + "」" + 补充;
  }
  return 文字;
}

function 内容是否通过(原因列表, 种类) {
  if (种类 !== "越权") return 原因列表.length === 0;
  // 回答准确率只看用户看到的回复。调用过程那一面单独决定整行过不过。
  return 原因列表.every(function (原因) { return 原因.indexOf("调用过程") === -1 && 原因.indexOf("接口") === -1; });
}

