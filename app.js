// ---------- 小工具（只做计算，不含规则） ----------

// 从句子里提取"疑似运单号"：
//   优先找以 1Z 开头的一串字母数字；
//   找不到的话，再找"长度 ≥ 10 且含数字"的一串（可能是用户把单号输错了）。
//   中文、空格、标点都会把字符串断开，所以"1Z999AA10123456784到哪了"也能提取。
function 提取疑似单号(用户输入) {
  var 词列表 = 用户输入.match(/[0-9A-Za-z]+/g) || [];
  var i;
  for (i = 0; i < 词列表.length; i++) {
    if (/^1Z/i.test(词列表[i])) return 词列表[i].toUpperCase();
  }
  for (i = 0; i < 词列表.length; i++) {
    if (词列表[i].length >= 10 && /\d/.test(词列表[i])) return 词列表[i].toUpperCase();
  }
  return null;
}

// 在 data.js 里按运单号查轨迹，没有则返回 null
function 查询轨迹(运单号) {
  for (var i = 0; i < 物流轨迹列表.length; i++) {
    if (物流轨迹列表[i].运单号 === 运单号) return 物流轨迹列表[i];
  }
  return null;
}

// 渠道原始状态 → 标准状态（映射表里没有就返回 null）
function 转标准状态(渠道原始状态) {
  var 映射 = 状态映射表[渠道原始状态];
  return 映射 ? 映射.标准状态 : null;
}

// 模拟调用一次渠道接口：耗时超过 配置.接口超时毫秒 就算超时（不真等）
function 调用渠道接口(轨迹) {
  return { 超时: 轨迹.接口响应耗时 > 配置.接口超时毫秒 };
}

// 距离上次更新过了多少小时（按"更新时间"字符串算）
function 距上次更新小时(轨迹) {
  var 更新时刻 = new Date(轨迹.更新时间.replace(" ", "T"));
  return (Date.now() - 更新时刻.getTime()) / (60 * 60 * 1000);
}

function 文本回答(文字) {
  return { 类型: "文本", 行: [{ 标签: "", 内容: 文字 }] };
}

// 右边面板的一步。结果只有三种：成功（绿）、失败（红）、警告（橙）
function 步骤(负责方, 做了什么, 结果) {
  return { 负责方: 负责方, 做了什么: 做了什么, 结果: 结果 || "成功" };
}

function 带步骤(回答, 步骤列表) {
  回答.步骤 = 步骤列表;
  return 回答;
}

// "查不到"和"越权"共用的唯一回复：两种情况对外长得一模一样，
// 这样没人能通过回复内容判断某个单号是否真的存在。
// 以后要改这句话，只改这一处。
function 查不到回答() {
  return 文本回答(回复模板.查不到);
}

// 组装"正常结果"：第 6、7 条规则（状态码没见过、断更）也在这里处理，
// 这样"正常回答"和"超时后的补推"用的是同一套逻辑。
// 前缀：补推时传 "【补推】"，平时传 ""
function 组装查询结果(轨迹, 前缀) {
  var 标准状态 = 转标准状态(轨迹.渠道原始状态);
  var 行 = [];

  if (标准状态) {
    行.push({ 标签: "结论", 内容: 前缀 + "运单 " + 轨迹.运单号 + " 当前状态：", 状态: 标准状态 });
  } else {
    // 【规则 6】状态码没见过：不猜，标准状态写"状态待确认"
    标准状态 = 回复模板.未知状态;
    行.push({ 标签: "结论", 内容: 前缀 + "运单 " + 轨迹.运单号 + " 当前状态：", 状态: 标准状态 });
  }

  行.push({
    标签: "依据",
    内容: "最新节点：" + 轨迹.最新节点 + "；更新时间：" + 轨迹.更新时间 + "；承运商：" + 轨迹.承运商
  });

  if (标准状态 === "状态待确认") {
    // 【规则 6】建议行换成"转人工"提示
    行.push({ 标签: "建议", 内容: 回复模板.未知状态建议 });
  } else {
    行.push({ 标签: "建议", 内容: 建议模板[标准状态] });
  }

  // 【规则 7】断更：不是"已签收"，且距今超过 48 小时
  if (标准状态 !== "已签收" && 距上次更新小时(轨迹) > 配置.长时间未更新小时) {
    行.push({ 标签: "提醒", 内容: 回复模板.断更提醒 });
  }

  return { 类型: "正常", 状态: 标准状态, 行: 行 };
}

/**
 * 回答的总入口：给定用户输入和当前账号，同时返回两样东西：
 *   1. 给用户看的回答（行）
 *   2. 给右边面板看的步骤列表（步骤）
 *
 * 返回格式：
 *   { 类型, 行, 步骤: [ {负责方, 做了什么, 结果} ], 状态?, 补推? }
 *   结果：成功（绿）/ 失败（红）/ 警告（橙）
 *   超时的回答会多带一个 补推：{ 延迟毫秒, 回答 }，页面到点再发出去
 *
 * 步骤在出问题的那一步停下（该步标红），后面的步骤不放进列表。
 * 两个例外：状态码未识别停在第 6 步标红后，仍继续第 7、8 步；
 * 断更是在第 7 步前多插一步橙色的"规则"，不算失败。
 *
 * 判断顺序（一条一条来，命中就直接 return）：
 *   规则 8 转人工 → 规则 1/9 没单号 → 规则 2 格式 → 规则 3 越权（回复同"查不到"）
 *   → 规则 4 超时 → 规则 5 查不到 → 规则 6/7 在下面和 组装查询结果() 里
 */
function 生成回答(用户输入, 当前账号) {
  var 步骤列表 = [
    步骤("模型（模拟）", "读取用户问题：「" + 用户输入 + "」")
  ];

  // 【规则 8】用户发"转人工"：只走前两步
  if (用户输入.indexOf("转人工") !== -1) {
    步骤列表.push(步骤("模型（模拟）", "判断结果：用户要求转人工"));
    return 带步骤(文本回答(回复模板.转人工), 步骤列表);
  }

  var 疑似单号 = 提取疑似单号(用户输入);

  if (!疑似单号) {
    // 【规则 9】跟订单、库存、物流都无关（比如天气）：只走前两步
    var 相关 = 业务关键词.some(function (词) { return 用户输入.indexOf(词) !== -1; });
    if (!相关) {
      步骤列表.push(步骤("模型（模拟）", "判断结果：问题与订单、库存、物流无关"));
      return 带步骤(文本回答(回复模板.范围外), 步骤列表);
    }
    // 【规则 1】缺单号：停在第 3 步
    步骤列表.push(步骤("模型（模拟）", "判断要查物流轨迹"));
    步骤列表.push(步骤("模型（模拟）", "没有抽取到运单号，无法继续查询", "失败"));
    return 带步骤(文本回答(回复模板.缺单号), 步骤列表);
  }

  // 【规则 2】单号格式不对：停在第 3 步
  if (!配置.运单号格式.test(疑似单号)) {
    步骤列表.push(步骤("模型（模拟）", "判断要查物流轨迹"));
    步骤列表.push(步骤("模型（模拟）", "抽取到 " + 疑似单号 + "，格式不对（应为 1Z 开头加 16 位字母数字）", "失败"));
    return 带步骤(文本回答(回复模板.格式不对), 步骤列表);
  }

  步骤列表.push(步骤("模型（模拟）", "判断要查物流轨迹"));
  步骤列表.push(步骤("模型（模拟）", "抽取运单号 " + 疑似单号 + "，格式校验通过"));

  var 轨迹 = 查询轨迹(疑似单号);

  // 【规则 3】越权：停在第 4 步。
  // 左边给用户的回复必须和"查不到"一字不差（共用 查不到回答()），不能带状态、节点、承运商。
  // 右边是内部日志，可以写真实原因，但不能再往下走第 5 步。
  if (轨迹 && 轨迹.所属仓库 !== 当前账号.绑定仓库) {
    步骤列表.push(步骤(
      "工具层",
      "当前账号绑定 " + 当前账号.绑定仓库 + " 仓，该运单属于 " + 轨迹.所属仓库 + " 仓。该运单不属于当前账号绑定的仓库，已拦截。对用户返回与“查不到”相同的话术，不透露任何信息（内部日志，用户看不到）",
      "失败"
    ));
    return 带步骤(查不到回答(), 步骤列表);
  }

  // 【规则 4】接口超时：停在第 5 步。先自动重试一次，仍然超时就走兜底，并安排补推
  if (轨迹 && 调用渠道接口(轨迹).超时) {
    var 重试结果 = 调用渠道接口(轨迹); // 自动重试一次（模拟，不真等）
    if (重试结果.超时) {
      步骤列表.push(步骤("工具层", "当前账号绑定 " + 当前账号.绑定仓库 + " 仓，该运单属于 " + 轨迹.所属仓库 + " 仓，鉴权通过"));
      步骤列表.push(步骤(
        "接口",
        "调用物流接口，耗时 " + 轨迹.接口响应耗时 + " 毫秒，超过 " + 配置.接口超时毫秒 + " 毫秒，自动重试 1 次，仍超时，返回兜底话术，后台约 1 分钟后重试并补推",
        "失败"
      ));
      var 兜底 = 文本回答(回复模板.超时兜底);
      兜底.补推 = {
        延迟毫秒: 配置.补推延迟毫秒,
        回答: 组装查询结果(轨迹, "【补推】")
      };
      return 带步骤(兜底, 步骤列表);
    }
  }

  // 【规则 5】查不到：停在第 5 步。回复里不能出现任何状态词
  if (!轨迹) {
    步骤列表.push(步骤("工具层", "当前账号绑定 " + 当前账号.绑定仓库 + " 仓，没有发现该运单属于其他仓库，鉴权通过"));
    步骤列表.push(步骤("接口", "未找到该运单", "失败"));
    return 带步骤(查不到回答(), 步骤列表);
  }

  // 正常流程：8 步。规则 6、7 加在第 6 步和第 7 步之间
  步骤列表.push(步骤("工具层", "当前账号绑定 " + 当前账号.绑定仓库 + " 仓，该运单属于 " + 轨迹.所属仓库 + " 仓，鉴权通过"));
  步骤列表.push(步骤("接口", "调用物流接口，耗时 " + 轨迹.接口响应耗时 + " 毫秒"));

  var 标准状态 = 转标准状态(轨迹.渠道原始状态);
  if (标准状态) {
    步骤列表.push(步骤("工具层", "渠道原始状态 " + 轨迹.渠道原始状态 + " → 标准状态 " + 标准状态));
  } else {
    // 【规则 6】状态码没见过：第 6 步标红，但不停下，后面的第 7、8 步照常走
    步骤列表.push(步骤("工具层", "渠道原始状态 " + 轨迹.渠道原始状态 + "，映射表里没有该状态码，标记为状态待确认，不猜测", "失败"));
  }

  var 回答 = 组装查询结果(轨迹, "");

  // 【规则 7】断更：插在"生成回答"之前，橙色，不算失败
  if (回答.状态 !== "已签收" && 距上次更新小时(轨迹) > 配置.长时间未更新小时) {
    步骤列表.push(步骤("规则", "距更新时间超过 " + 配置.长时间未更新小时 + " 小时，标记为轨迹异常", "警告"));
  }

  步骤列表.push(步骤("模型（模拟）", "生成回答，只复述接口返回的数据"));
  步骤列表.push(步骤("系统", "写日志"));
  return 带步骤(回答, 步骤列表);
}


