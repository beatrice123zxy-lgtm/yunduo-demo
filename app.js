function 检查有没有编造(文字, 轨迹, 原因) {
  if (文字.indexOf(轨迹.最新节点) === -1) 原因.push("回复没有包含这条运单的最新节点");
  if (文字.indexOf(轨迹.承运商) === -1) 原因.push("回复没有包含这条运单的承运商");
  物流轨迹列表.forEach(function (其他) {
    if (其他.运单号 !== 轨迹.运单号 && 其他.最新节点 !== 轨迹.最新节点 && 文字.indexOf(其他.最新节点) !== -1) {
      原因.push("回复出现了其他运单的节点");
    }
  });
}

// 正常回答 / 断更：状态来自映射表，建议来自建议模板，断更那句来自回复模板
function 检查正常或断更(回答, 轨迹, 要断更) {
  var 原因 = [];
  var 文字 = 用户可见文字(回答);
  var 期望状态 = 转标准状态(轨迹.渠道原始状态);
  if (回答.状态 !== 期望状态) {
    原因.push("标准状态应为「" + 期望状态 + "」，实际是「" + (回答.状态 || "无") + "」");
  }
  if (期望状态 && 文字.indexOf(建议模板[期望状态]) === -1) 原因.push("没有使用该状态的建议模板");
  检查有没有编造(文字, 轨迹, 原因);
  if (要断更) {
    if (文字.indexOf("超过 48 小时") === -1 || 文字.indexOf(回复模板.断更提醒) === -1) {
      原因.push("缺少断更提示「" + 回复模板.断更提醒 + "」");
    }
  } else if (文字.indexOf(回复模板.断更提醒) !== -1) {
    原因.push("不该出现超过 48 小时的提示");
  }
  return 原因;
}

