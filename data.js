// ---------- 辅助函数：生成"N 小时前"的时间字符串 ----------
function 距今小时(小时数) {
  var 时间 = new Date(Date.now() - 小时数 * 60 * 60 * 1000);
  var 补零 = function (n) { return n < 10 ? "0" + n : "" + n; };
  return (
    时间.getFullYear() + "-" + 补零(时间.getMonth() + 1) + "-" + 补零(时间.getDate()) +
    " " + 补零(时间.getHours()) + ":" + 补零(时间.getMinutes()) + ":" + 补零(时间.getSeconds())
  );
}

